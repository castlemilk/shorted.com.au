/**
 * Generalized basket baker — pre-computes a short-position series for ANY set of
 * ASX codes so the newsroom can commission sector basket pieces (lithium, iron
 * ore, supermarkets, …). Same shorts × stock_prices weekly join as the banks
 * bake; emits a unified BasketDef the registry (data/short-baskets.ts) picks up.
 *
 * Run:
 *   cd scripts/take-writer
 *   DATABASE_URL=$(gcloud secrets versions access latest --secret=DATABASE_URL \
 *     --project=rosy-clover-477102-t5 --account=ben@shorted.com.au) \
 *   npx tsx src/bake-short-basket.ts --key=lithium --label="Lithium & battery materials" \
 *     --codes=PLS,MIN,LTR,IGO
 *
 * Codes are stacked bottom→top in the order given — pass the largest-$ first.
 */
import { Pool } from "pg";
import { writeFileSync } from "fs";
import { resolve } from "path";

const WEEKS = 104;

function arg(name: string): string | undefined {
  const hit = process.argv.find((a) => a.startsWith(`--${name}=`));
  return hit?.slice(name.length + 3);
}

const key = arg("key");
const label = arg("label") ?? key;
const codes = (arg("codes") ?? "")
  .split(",")
  .map((c) => c.trim().toUpperCase())
  .filter(Boolean);

if (!key || codes.length < 2) {
  console.error('Usage: --key=lithium --label="…" --codes=PLS,MIN,LTR,IGO');
  process.exit(1);
}

const OUT = resolve(
  process.cwd(),
  `../../web/src/@/components/news/mdx/data/short-basket-${key}.ts`,
);

const SQL = `
WITH base AS (
  SELECT "PRODUCT_CODE" code, date_trunc('week', "DATE") wk, "DATE"::date d,
         "PERCENT_OF_TOTAL_PRODUCT_IN_ISSUE_REPORTED_AS_SHORT_POSITIONS" pct,
         "REPORTED_SHORT_POSITIONS" shares
  FROM shorts
  WHERE "PRODUCT_CODE" = ANY($1) AND "DATE" >= now() - interval '${WEEKS} weeks'
),
wk AS (
  SELECT DISTINCT ON (code, wk) code, wk::date AS week, d, pct, shares
  FROM base ORDER BY code, wk, d DESC
),
priced AS (
  SELECT wk.week, wk.code, wk.pct,
         round((wk.shares * p.close)::numeric / 1e9, 4) AS val_bn
  FROM wk
  LEFT JOIN LATERAL (
    SELECT close FROM stock_prices sp
    WHERE sp.stock_code = wk.code AND sp.date <= wk.d
    ORDER BY sp.date DESC LIMIT 1
  ) p ON true
)
SELECT week::text AS week, code,
       round(pct::numeric, 3) AS pct, val_bn
FROM priced ORDER BY week ASC;
`;

interface Row { week: string; code: string; pct: number | string | null; val_bn: number | string | null; }

function forwardFill(arr: (number | null)[], lbl: string): number[] {
  let last = 0, leading = 0, seen = false, filled = 0;
  const out = arr.map((v) => {
    if (v == null || Number.isNaN(v)) {
      if (!seen) leading++;
      filled++;
      return last;
    }
    seen = true;
    last = v;
    return v;
  });
  if (filled > 0) {
    console.warn(
      `forward-fill: ${lbl} patched ${filled} week(s)` +
        (leading > 0 ? ` (${leading} leading zeros — band starts flat!)` : ""),
    );
  }
  return out;
}

async function main() {
  const pool = new Pool({ connectionString: process.env.DATABASE_URL });
  const { rows } = await pool.query<Row>(SQL, [codes]);
  await pool.end();

  // Build the shared weekly spine (union of all weeks present).
  const weeks = Array.from(new Set(rows.map((r) => r.week))).sort();
  const dates = weeks.map((w) => new Date(w + "T00:00:00Z").getTime());
  const idxOf = new Map(weeks.map((w, i) => [w, i]));
  const num = (v: number | string | null) => (v == null ? null : Number(v));

  const pct: Record<string, number[]> = {};
  const dollar: Record<string, number[]> = {};
  for (const c of codes) {
    const p: (number | null)[] = new Array(weeks.length).fill(null);
    const d: (number | null)[] = new Array(weeks.length).fill(null);
    for (const r of rows) {
      if (r.code !== c) continue;
      const i = idxOf.get(r.week)!;
      p[i] = num(r.pct);
      d[i] = num(r.val_bn);
    }
    pct[c] = forwardFill(p, `${c} pct`);
    dollar[c] = forwardFill(d, `${c} val`);
  }

  if (weeks.length < 10) throw new Error(`Too few weeks (${weeks.length}) — aborting bake`);

  // Peak summed-dollar point = the record basket.
  let recordValueBn = -1, recIdx = 0;
  for (let i = 0; i < dates.length; i++) {
    const sum = codes.reduce((s, c) => s + (dollar[c]![i] ?? 0), 0);
    if (sum > recordValueBn) { recordValueBn = sum; recIdx = i; }
  }
  recordValueBn = Number(recordValueBn.toFixed(3));

  const asOf = weeks[weeks.length - 1]!;
  const latest = codes.reduce((s, c) => s + dollar[c]![dates.length - 1]!, 0);
  const banner =
    `// AUTO-GENERATED by scripts/take-writer/src/bake-short-basket.ts — DO NOT EDIT BY HAND.\n` +
    `// ${label} · short value = REPORTED_SHORT_POSITIONS × last close, weekly ASIC data.\n` +
    `// key=${key} · codes=${codes.join(",")} · asOf=${asOf} · weeks=${dates.length} · latest=$${latest.toFixed(2)}bn · record=$${recordValueBn}bn\n`;

  const body = `${banner}
import type { BasketDef } from "./short-baskets-types";

export const BASKET: BasketDef = ${JSON.stringify(
    { key, label, asOf, codes, dates, pct, dollar, recordValueBn, recordDate: dates[recIdx] },
    null,
    2,
  )};
`;

  writeFileSync(OUT, body);
  console.log(`Wrote ${OUT}`);
  console.log(banner.trim());
}

main().catch((e) => { console.error(e); process.exit(1); });
