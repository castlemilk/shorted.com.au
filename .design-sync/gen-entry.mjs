// Durable sync input for /design-sync (package shape).
//
// web/ is a Next.js app, not a component library: there is no built dist/ and
// no library entry, so the converter has nothing to bundle. This script builds
// one — a curated barrel of the web/src/@/components/ui modules that actually
// bundle to a browser IIFE — and prints the card roster for config.json's
// componentSrcMap.
//
// Inclusion is PROBED, not pattern-matched: each module is bundled with esbuild
// (browser platform, react externalised) and kept only if it resolves. That is
// what excludes the next-auth-coupled modules, whose import graph reaches
// jwks-rsa and pulls node builtins the browser bundle cannot satisfy.
//
//   node .design-sync/gen-entry.mjs            # writes web/.ds-sync-entry.tsx
//   node .design-sync/gen-entry.mjs --roster   # also prints the roster JSON
//
// The entry it writes is generated + gitignored; THIS file is the durable input.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const REPO = resolve(import.meta.dirname, '..');
const DS = join(REPO, '.ds-sync');
const UI_REL = 'src/@/components/ui';
const UI = join(REPO, 'web', UI_REL);

const { build } = await import(join(DS, 'node_modules/esbuild/lib/main.js'));
const { tsconfigPathsPlugin, reactShim } = await import(join(DS, 'lib/bundle.mjs'));
const { Project, Node, ts } = await import(join(DS, 'node_modules/ts-morph/dist/ts-morph.js'));


