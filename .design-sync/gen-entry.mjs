// The tsconfig-paths plugin JSON.parses its config directly and does NOT follow
// `extends`, so the alias file must carry the app's full paths map inline. It
// exists to alias "next/image" (exact match, no wildcard) to the interop shim.
//
// Parse with TypeScript's own JSONC parser, never a comment-stripping regex:
// the naive /\/\*[\s\S]*?\*\// sweep treats the "**/*.ts" globs in this
// tsconfig's `include` as a block comment and silently mangles the JSON.
{
  const text = readFileSync(join(REPO, 'web/tsconfig.json'), 'utf8');
  const parsed = ts.parseConfigFileTextToJson('tsconfig.json', text);
  if (parsed.error) throw new Error('cannot parse web/tsconfig.json');
  const { paths = {}, baseUrl = '.' } = parsed.config.compilerOptions ?? {};
  writeFileSync(join(REPO, 'web/.ds-sync-paths.json'), JSON.stringify({
    _generated: 'by .design-sync/gen-entry.mjs - do not edit, do not commit',
    compilerOptions: { baseUrl, paths: { ...paths, 'next/image': ['./.ds-sync-next-image.tsx'] } },
  }, null, 2) + '\n');
}


// ---------------------------------------------------------------------------
// cva variant props: make them OWN props again.
//
// A cva component's variants ARE declared in this package (tsc emits them as an
// inline object literal in the component's own .d.ts), but they reach the props
// type through `VariantProps<...>`, which is a MAPPED type. Properties of a
// mapped type carry synthesized declarations that resolve into
// class-variance-authority, so the converter's isOwnProp filter drops them and
// `variant`/`size` - this design system's core vocabulary - silently vanish from
// every card's API contract, which is what the design agent codes against.
//
// Re-declaring them as literal members of `<Name>Props` makes them own props, so
// the converter picks them up by itself. This replaces hand-written
// cfg.dtsPropsFor entries, which had to be re-checked by hand whenever a cva
// variant list changed and went stale with no warning.
function inlineCvaVariantProps(typesDir) {
  const CLASS_PROP = 'ClassProp';
  let patched = 0;
  const walkDts = (dir) => {
    for (const e of readdirSync(dir, { withFileTypes: true })) {
      const p = join(dir, e.name);
      if (e.isDirectory()) { walkDts(p); continue; }
      if (!e.name.endsWith('.d.ts')) continue;

      let text = readFileSync(p, 'utf8');
      const original = text;

      // Every `props?: { ... } & ...ClassProp` block is a cva variant bag.
      // Brace-match rather than regex the body: the unions contain no braces,
      // but the surrounding declaration does.
      const blocks = [];
      let i = 0;
      while ((i = text.indexOf('props?: {', i)) !== -1) {
        const open = text.indexOf('{', i);
        let depth = 0, j = open;
        for (; j < text.length; j++) {
          if (text[j] === '{') depth++;
          else if (text[j] === '}' && --depth === 0) break;
        }
        const body = text.slice(open + 1, j);
        const tail = text.slice(j, j + 200);
        if (tail.includes(CLASS_PROP)) blocks.push({ start: i, body });
        i = j + 1;
      }
      if (!blocks.length) continue;

      for (const { start, body } of blocks) {
        // Which component owns this bag? Either `declare const fooVariants` just
        // before it, or the `declare const Foo:` the inline VariantProps sits in.
        const before = text.slice(0, start);
        const viaVariants = [...before.matchAll(/declare const (\w+)Variants\s*:/g)].pop();
        const viaConst = [...before.matchAll(/declare (?:const|function) ([A-Z]\w*)\b/g)].pop();
        const name = viaVariants
          ? viaVariants[1][0].toUpperCase() + viaVariants[1].slice(1)
          : viaConst?.[1];
        if (!name) continue;

        // Keep only the real variant members (skip `class`/`className`).
        const members = body
          .split('\n')
          .map((l) => l.trim())
          .filter((l) => /^\w+\?:/.test(l) && !/^class(Name)?\?:/.test(l))
          .join('\n  ');
        if (!members) continue;

        const iface = new RegExp(`interface ${name}Props([^{]*)\\{`);
        const m = text.match(iface);
        if (m) {
          if (text.slice(m.index).startsWith(m[0] + '\n  ' + members)) continue; // idempotent
          text = text.replace(iface, `${m[0]}\n  ${members}`);
        } else {
          text += `\nexport interface ${name}Props extends React.HTMLAttributes<HTMLElement> {\n  ${members}\n}\n`;
        }
        patched++;
      }
      if (text !== original) writeFileSync(p, text);
    }
  };
  walkDts(typesDir);
  console.error(`cva variant props inlined into ${patched} props type(s)`);
}

const files = readdirSync(UI).filter((f) => /\.tsx$/.test(f) && !/\.(stories|test|spec)\./.test(f));
const paths = tsconfigPathsPlugin(join(REPO, 'web/tsconfig.json'));

const clean = [], failed = [];
for (const f of files) {
  try {
    await build({
      entryPoints: [join(UI, f)], bundle: true, write: false, platform: 'browser', target: 'es2020',
      nodePaths: [join(REPO, 'web/node_modules')], plugins: [paths, reactShim].filter(Boolean),
      logLevel: 'silent', format: 'esm', jsx: 'automatic',
      loader: { '.svg': 'dataurl', '.png': 'dataurl', '.woff': 'dataurl', '.woff2': 'dataurl', '.css': 'text' },
    });
    clean.push(f);
  } catch (e) { failed.push([f, (e.errors ?? [])[0]?.text ?? String(e).slice(0, 80)]); }
}

// Card roster: one entry per PRIMARY component. Compound parts (DialogContent,
// CardHeader, …) stay on window.Shorted via the barrel but get no card of their
// own — 180+ cards of sub-parts is noise, and they are documented on the parent.
const project = new Project({ skipAddingFilesFromTsConfig: true,
  compilerOptions: { jsx: ts.JsxEmit.Preserve, allowJs: true, skipLibCheck: true } });
const pascal = (f) => f.replace(/\.tsx$/, '').split(/[-_]/).map((s) => s[0].toUpperCase() + s.slice(1)).join('');
const included = [], roster = {}, defaultExports = [];
let exports_ = 0;
for (const f of clean) {
  const sf = project.addSourceFileAtPathIfExists(join(UI, f));
  if (!sf) continue;
  const names = new Set();
  let defaultName = null;
  for (const [name, decls] of sf.getExportedDeclarations()) {
    const real = name === 'default' ? decls.map((d) => d.getName?.()).find((n) => n && n !== 'default') : name;
    if (!real || !/^[A-Z][A-Za-z0-9]*$/.test(real)) continue;
    if (decls.some((d) => Node.isVariableDeclaration(d) || Node.isFunctionDeclaration(d) || Node.isClassDeclaration(d))) {
      names.add(real);
      // `export * from` does NOT re-export `default`, so a default-exported
      // component lands on the roster (it IS a .d.ts export) but never on
      // window.Shorted — that is [BUNDLE_EXPORT] "not a component on
      // window.<Global>". Re-export it by name explicitly.
      if (name === 'default') defaultName = real;
    }
  }
  if (!names.size) continue;
  if (defaultName) defaultExports.push([defaultName, f]);
  included.push(f); exports_ += names.size;
  const want = pascal(f);
  const primary = names.has(want) ? [want]
    : [...names].filter((n) => ![...names].some((o) => o !== n && n.startsWith(o)));
  // Primary -> src path (a card). Every other export -> null, which EXCLUDES it
  // from the roster: componentSrcMap only ever ADDS to the .d.ts-derived set,
  // so compound parts must be excluded by name or they each get their own card.
  for (const n of names) roster[n] = primary.includes(n) ? `${UI_REL}/${f}` : null;
}

writeFileSync(join(REPO, 'web/.ds-sync-entry.tsx'),
  '// GENERATED by .design-sync/gen-entry.mjs — do not edit, do not commit.\n' +
  '// Curated barrel of the browser-bundleable primitives in src/@/components/ui.\n' +
  '// Every name here lands on window.Shorted; the card roster is the curated\n' +
  '// subset in .design-sync/config.json componentSrcMap.\n' +
  // MUST be first: the shim installs globalThis.process before any component
  // module body runs. See .ds-sync-process-shim.ts for why.
  'import "./.ds-sync-process-shim";\n' +
  included.map((f) => `export * from "./${UI_REL}/${f.replace(/\.tsx$/, '')}";`).join('\n') + '\n' +
  defaultExports.map(([n, f]) => `export { default as ${n} } from "./${UI_REL}/${f.replace(/\.tsx$/, '')}";`).join('\n') + '\n');

console.error(`entry: ${included.length} modules, ${exports_} exports → web/.ds-sync-entry.tsx`);
console.error(`roster: ${Object.keys(roster).length} cards`);
console.error(`excluded (${failed.length}): ${failed.map(([f, w]) => `${f} (${w.slice(0, 40)})`).join(', ')}`);
if (process.argv.includes('--roster')) console.log(JSON.stringify(Object.fromEntries(Object.entries(roster).sort()), null, 2));

if (process.argv.includes('--inline-cva')) inlineCvaVariantProps(join(REPO, 'web/.ds-types'));
