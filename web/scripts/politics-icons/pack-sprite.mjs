// Politics iconography — sprite packer.
//
// Packs ./out/<id>.png (produced by generate-icons-openai.mjs) into:
//   - web/public/politics-icons/politics-icons.png                     (the sprite sheet)
//   - web/src/@/components/politicians/politics-icons.generated.ts     (typed manifest + name union)
//
// Grid coords are deterministic (config order), so this can run before every icon
// exists — missing cells are left transparent and the manifest still typechecks.
//
// Usage: node web/scripts/politics-icons/pack-sprite.mjs
import { writeFileSync, mkdirSync, existsSync } from "node:fs";
import { createHash } from "node:crypto";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";
import { ICONS } from "./icon-set.config.mjs";

const HERE = dirname(fileURLToPath(import.meta.url));
const OUT = join(HERE, "out");
const WEB = join(HERE, "..", "..");
const PUBLIC_DIR = join(WEB, "public", "politics-icons");
const SPRITE_PATH = join(PUBLIC_DIR, "politics-icons.png");
const MANIFEST_TS = join(WEB, "src", "@", "components", "politicians", "politics-icons.generated.ts");

const CELL = 128; // source cell px (@2x-ish for ≤64px display); crisp when downscaled
const COLS = 6;
const rows = Math.ceil(ICONS.length / COLS);
const WIDTH = COLS * CELL;
const HEIGHT = rows * CELL;

mkdirSync(PUBLIC_DIR, { recursive: true });

const coords = {};
const composites = [];
let present = 0;
for (let i = 0; i < ICONS.length; i++) {
  const id = ICONS[i].id;
  const col = i % COLS, row = Math.floor(i / COLS);
  const x = col * CELL, y = row * CELL;
  coords[id] = { x, y };
  const src = join(OUT, `${id}.png`);
  if (existsSync(src)) {
    const buf = await sharp(src)
      .resize(CELL, CELL, { fit: "contain", background: { r: 0, g: 0, b: 0, alpha: 0 } })
      .png()
      .toBuffer();
    composites.push({ input: buf, left: x, top: y });
    present += 1;
  }
}

const sheet = await sharp({ create: { width: WIDTH, height: HEIGHT, channels: 4, background: { r: 0, g: 0, b: 0, alpha: 0 } } })
  .composite(composites)
  .png({ compressionLevel: 9 })
  .toBuffer();
writeFileSync(SPRITE_PATH, sheet);

const hash = createHash("sha1").update(sheet).digest("hex").slice(0, 8);
const iconsLiteral = Object.entries(coords)
  .map(([id, { x, y }]) => `    ${JSON.stringify(id)}: { x: ${x}, y: ${y} },`)
  .join("\n");
const groupsLiteral = Object.entries(
  ICONS.reduce((acc, ic) => {
    (acc[ic.group] ??= []).push(ic.id);
    return acc;
  }, {}),
)
  .map(([group, ids]) => `    ${JSON.stringify(group)}: [${ids.map((i) => JSON.stringify(i)).join(", ")}],`)
  .join("\n");

const ts = `// GENERATED by web/scripts/politics-icons/pack-sprite.mjs — do not edit by hand.
// Sprite of warm-duotone politics icons; coords are top-left px within the sheet.
// The subjects are an editorial artefact — see the header of
// web/scripts/politics-icons/icon-set.config.mjs before adding one.
export const POLITICS_ICONS = {
  sheet: "/politics-icons/politics-icons.png?v=${hash}",
  cell: ${CELL},
  width: ${WIDTH},
  height: ${HEIGHT},
  icons: {
${iconsLiteral}
  },
  groups: {
${groupsLiteral}
  },
} as const;

export type PoliticsIconName = keyof typeof POLITICS_ICONS.icons;
export type PoliticsIconGroup = keyof typeof POLITICS_ICONS.groups;
`;
writeFileSync(MANIFEST_TS, ts);

console.error(`packed ${present}/${ICONS.length} icons -> ${SPRITE_PATH} (${WIDTH}x${HEIGHT}, v=${hash})`);
console.error(`manifest -> ${MANIFEST_TS}`);
if (present < ICONS.length) {
  const missing = ICONS.filter((ic) => !existsSync(join(OUT, `${ic.id}.png`))).map((ic) => ic.id);
  console.error(`missing (${missing.length}): ${missing.join(", ")}`);
}
