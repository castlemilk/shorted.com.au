#!/usr/bin/env node
// Bundles the admin console's private API docs (/admin/api-docs) into one
// server module, src/server/private-docs/docs.generated.ts, so the page reads
// them from code rather than from files a deployment might not trace.
//
// The sources:
//   - src/server/private-docs/market-moves-api.md  hand-written: the market-moves posting API
//   - src/server/private-docs/private-api.md       generated: `node scripts/generate-api-markdown.mjs --private`
//   - ../docs/mcp-admin.md                          the admin MCP connector's reference
//
// Run with `npm run docs:private` (make openapi runs it). Never write these under
// public/: nothing may serve them without the admin login.
// src/server/private-docs/__tests__/docs-generated.test.ts fails when the bundle
// is out of date with its sources.
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");

export const PRIVATE_DOC_SOURCES = [
  {
    slug: "market-moves",
    title: "Market moves posting API",
    description:
      "POST /v1/market-moves and /retract with a console token, every field and its rule, the answers, and the read rpc. Hand this to the market-moves workflow.",
    file: "src/server/private-docs/market-moves-api.md",
  },
  {
    slug: "private-api",
    title: "Private Connect API",
    description:
      "Every rpc that needs a credential, signed-in or admin, generated from the protos with request fields and curl examples.",
    file: "src/server/private-docs/private-api.md",
  },
  {
    slug: "admin-mcp",
    title: "Admin MCP connector",
    description: "The /mcp/admin tools, their scopes and how to connect them (docs/mcp-admin.md).",
    file: "../docs/mcp-admin.md",
  },
];

const docs = PRIVATE_DOC_SOURCES.map(({ file, ...doc }) => ({
  ...doc,
  markdown: readFileSync(path.join(root, file), "utf8"),
}));

const out = `// GENERATED by web/scripts/generate-private-docs.mjs (npm run docs:private). Do not edit.
// The admin console's private API docs, read only by app/admin/api-docs (behind
// requireAdmin). Never import this from a client module or a public route.

export interface PrivateDoc {
  slug: string;
  title: string;
  description: string;
  markdown: string;
}

export const PRIVATE_DOCS: PrivateDoc[] = ${JSON.stringify(docs, null, 2)};
`;

writeFileSync(path.join(root, "src/server/private-docs/docs.generated.ts"), out);
console.log(`wrote src/server/private-docs/docs.generated.ts (${docs.length} documents)`);
