// Stock picker editorial art: bake the masters into what the site serves.
//
// From ./out/<strategy-id>.png (generate-art.mjs or the OpenAI fallback):
//   web/public/picks-art/<id>.light.avif   the ~3:1 band, as drawn (light room)
//   web/public/picks-art/<id>.dark.avif    the same band through the dark gradient map
//   web/public/picks-art/og/<id>.jpg       1200x630, dark-toned, for the share card (satori decodes JPEG)
//   web/src/@/lib/strategies/art.generated.ts   the manifest: which strategies have art, with a content hash
//
// The palette work is the housing banners' (web/scripts/housing-banners/
// palette.mjs): one luminance master, two theme ramps, so there is one AI
// image per scene, not two. A strategy with no master is left OUT of the
// manifest (and any stale baked files for it are removed), so the site
// renders it without art rather than with a broken image.
//
// Usage: node web/scripts/picks-art/bake.mjs
import sharp from "sharp";
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { RAMPS, buildLut } from "../housing-banners/palette.mjs";
import { SCENES } from "./art-set.config.mjs";

const HERE = dirname(fileURLToPath(import.meta.url));
const OUT = join(HERE, "out");
const WEB = join(HERE, "..", "..");
const DEST = join(WEB, "public", "picks-art");
const OG_DEST = join(DEST, "og");
const MANIFEST_TS = join(WEB, "src", "@", "lib", "strategies", "art.generated.ts");
mkdirSync(OG_DEST, { recursive: true });

const BW = 1600, BH = 540; // the ~3:1 band
const OG_W = 1200, OG_H = 630; // next/og dimensions
const darkLut = buildLut(RAMPS.dark);

async function applyDarkLut(pipeline) {
  const { data, info } = await pipeline
    .greyscale()
    .linear(1.06, -7.68)
    .toColourspace("b-w")
    .raw()
    .toBuffer({ resolveWithObject: true });
  const rgb = Buffer.allocUnsafe(info.width * info.height * 3);
  for (let i = 0; i < info.width * info.height; i++) {
    const g = data[i] * 3;
    rgb[i * 3] = darkLut[g];
    rgb[i * 3 + 1] = darkLut[g + 1];
    rgb[i * 3 + 2] = darkLut[g + 2];
  }
  return sharp(rgb, { raw: { width: info.width, height: info.height, channels: 3 } });
}

// The band is cut from the upper-middle of the 3:2 master: the subject sits
// in the right two-thirds and the calm field upper-left, so a crop that
// keeps the top 28% margin keeps both.
async function bandFromMaster(id) {
  const full = await sharp(join(OUT, `${id}.png`)).resize(BW).toBuffer();
  const meta = await sharp(full).metadata();
  const top = Math.round((meta.height - BH) * 0.28);
  return sharp(full).extract({ left: 0, top: Math.max(0, top), width: BW, height: BH });
}

const manifest = {};
for (const { id } of SCENES) {
  const master = join(OUT, `${id}.png`);
  const files = [join(DEST, `${id}.light.avif`), join(DEST, `${id}.dark.avif`), join(OG_DEST, `${id}.jpg`)];
  if (!existsSync(master)) {
    for (const f of files) if (existsSync(f)) rmSync(f);
    console.error(`skip ${id} (no master; any baked files removed)`);
    continue;
  }
  await (await bandFromMaster(id)).avif({ quality: 62 }).toFile(files[0]);
  const darkBand = await applyDarkLut(await bandFromMaster(id));
  await darkBand.avif({ quality: 62 }).toFile(files[1]);
  const ogDark = await applyDarkLut(sharp(master).resize(OG_W, OG_H, { fit: "cover" }));
  await ogDark.jpeg({ quality: 72 }).toFile(files[2]);

  const hash = createHash("sha256");
  for (const f of files) hash.update(readFileSync(f));
  manifest[id] = { hash: hash.digest("hex").slice(0, 12) };
  console.error(`baked ${id} (${manifest[id].hash})`);
}

const entries = Object.entries(manifest)
  .map(([id, { hash }]) => `  ${JSON.stringify(id)}: { hash: ${JSON.stringify(hash)} },`)
  .join("\n");
const ts = `// GENERATED by web/scripts/picks-art/bake.mjs. Do not edit by hand.
//
// The strategies with baked editorial art under web/public/picks-art/ (one
// light and one dark AVIF band, and one dark JPEG for the share card), keyed
// by strategy id, with a content hash the URLs carry so a regeneration is
// never served from a stale cache. Empty until the art is generated and
// baked (web/scripts/picks-art/README.md); every reader renders without art
// for a strategy missing here.

export const STRATEGY_ART: Readonly<Record<string, { readonly hash: string }>> = {${
  entries ? `\n${entries}\n` : ""
}};
`;
writeFileSync(MANIFEST_TS, ts);
console.error(`DONE ${Object.keys(manifest).length}/${SCENES.length} baked -> ${DEST}; manifest -> ${MANIFEST_TS}`);
